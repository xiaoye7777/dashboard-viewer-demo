import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const { chromium } = createRequire(import.meta.url)('playwright')
const browser = await chromium.launch({ executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true })
const context = await browser.newContext({ viewport:{width:1440,height:1000} })
await context.addInitScript(() => {
  const urls=new Set(),frames=new Set(),create=URL.createObjectURL.bind(URL),revoke=URL.revokeObjectURL.bind(URL)
  URL.createObjectURL=(...args)=>{const url=create(...args);urls.add(url);return url};URL.revokeObjectURL=url=>{urls.delete(url);revoke(url)}
  const request=requestAnimationFrame.bind(window),cancel=cancelAnimationFrame.bind(window)
  window.requestAnimationFrame=fn=>{const id=request(time=>{frames.delete(id);fn(time)});frames.add(id);return id};window.cancelAnimationFrame=id=>{frames.delete(id);cancel(id)}
  window.sdkResources=()=>({urls:urls.size,raf:frames.size})
})
const page=await context.newPage(), errors=[], base=process.env.TEST_BASE_URL || 'http://127.0.0.1:5200'
page.on('pageerror',error=>errors.push(error.message))
try {
  await page.goto(base)
  await page.waitForSelector('[data-testid="twin-scene-viewer"][data-loaded="true"]')
  await page.waitForFunction(()=>document.querySelector('[data-testid="twin-scene-viewer"]')?.dataset.mockTicks > '0')
  assert.equal((await page.getByTestId('kpi-total').textContent()).trim(),'8')
  const sourceCheck=await page.evaluate(async()=>{const response=await fetch('/zero-carbon-demo.twin.zip');return {ok:response.ok,type:response.headers.get('content-type'),size:Number(response.headers.get('content-length')||0)}})
  assert(sourceCheck.ok&&sourceCheck.size>0)
  await page.evaluate(()=>{window.sdkViewer=document.querySelector('[data-testid="twin-scene-viewer"]').__vueParentComponent.exposed})
  const state=await page.evaluate(()=>{const s=window.sdkViewer.getRuntimeState();return {bindings:s.bindings.length,running:s.mockRunning,ticks:s.mockTickCount,values:Object.keys(s.runtimeValues).length,projectId:s.projectId}})
  assert.equal(state.bindings,8);assert(state.running&&state.values===40)
  const before=state.ticks;await page.waitForFunction(t=>window.sdkViewer.getRuntimeState().mockTickCount>t,before)
  await page.screenshot({path:'/tmp/dashboard-viewer-sdk-demo.png',fullPage:true})
  assert(await page.evaluate(()=>window.sdkViewer.selectDevice('ESS-001')))
  await page.waitForFunction(()=>window.sdkViewer.getSelection()?.deviceId==='ESS-001')
  const initialCanvas=await page.locator('[data-testid="twin-scene-viewer"] canvas').boundingBox()
  await page.mouse.click(initialCanvas.x+initialCanvas.width/2,initialCanvas.y+120)
  await page.waitForFunction(()=>window.sdkViewer.getSelection()===null)
  assert(await page.evaluate(()=>window.sdkViewer.focusDevice('ESS-001')))
  const canvas=await page.locator('[data-testid="twin-scene-viewer"] canvas').boundingBox()
  await page.mouse.click(canvas.x+canvas.width/2,canvas.y+canvas.height/2)
  await page.waitForFunction(()=>window.sdkViewer.getSelection()?.deviceId==='ESS-001')
  assert.equal(await page.getByTestId('dashboard-demo').getAttribute('data-selected-device-id'),'ESS-001')
  await page.waitForSelector('[data-testid="last-interaction-event"]')
  assert((await page.getByTestId('last-interaction-event').textContent()).includes('open-device-detail'))
  await page.getByTestId('device-ESS-002').click()
  await page.waitForFunction(()=>window.sdkViewer.getSelection()?.deviceId==='ESS-002')
  assert.equal(await page.getByTestId('dashboard-demo').getAttribute('data-selected-device-id'),'ESS-002')
  await page.screenshot({path:'/tmp/dashboard-viewer-sdk-focused.png',fullPage:true})
  await page.evaluate(()=>document.querySelector('#app').__vue_app__.unmount())
  await page.waitForTimeout(300)
  assert.deepEqual(await page.evaluate(()=>window.sdkResources()),{urls:0,raf:0})
  const assetPage=await context.newPage();assetPage.on('pageerror',error=>errors.push(error.message))
  await assetPage.goto(`${base}?package=/sdk-assets-fixture.twin.zip`)
  await assetPage.waitForSelector('[data-testid="twin-scene-viewer"][data-loaded="true"]')
  assert(Number(await assetPage.getByTestId('twin-scene-viewer').getAttribute('data-object-count'))>=2)
  assert.equal((await assetPage.evaluate(()=>window.sdkResources())).urls,2)
  await assetPage.evaluate(()=>document.querySelector('#app').__vue_app__.unmount());await assetPage.waitForTimeout(300)
  assert.deepEqual(await assetPage.evaluate(()=>window.sdkResources()),{urls:0,raf:0});await assetPage.close()
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({packageSource:sourceCheck,threeBindings:state.bindings,mockValues:state.values,primitive:'PASS',glb:'PASS',hdr:'PASS',viewerToDashboard:'PASS',dashboardToViewer:'PASS',interactionEvent:'PASS',dispose:'PASS: Object URLs and RAF released',screenshot:'/tmp/dashboard-viewer-sdk-demo.png'},null,2))
} finally {await context.close();await browser.close()}
